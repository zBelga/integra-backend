-- Quem saiu da planilha mas foi mantido por ter documento/histórico:
select c.nome, c.numero_chapa,
       (select count(*) from documentos d where d.colaborador_id = c.id) as documentos,
       (select count(*) from documento_historico h where h.colaborador_id = c.id) as historico
  from colaboradores c
 where c.empresa_id = 'emp-928389'
   and (exists (select 1 from documentos d where d.colaborador_id = c.id)
     or exists (select 1 from documento_historico h where h.colaborador_id = c.id))
 order by c.nome;
